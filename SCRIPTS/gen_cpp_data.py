_MAX_SECONDARY_STAT_CHANGES = 5
_MAX_SELF_STAT_CHANGES = 3


def _validate_stat_change_lengths() -> None:
    """Fail loud if any move exceeds the assumed max array sizes."""
    for move, d in MOVE_DATA.items():
        for sec in (d.secondary, d.secondary2):
            if sec is not None and len(sec.stat_changes) > _MAX_SECONDARY_STAT_CHANGES:
                raise ValueError(
                    f"{move.name} secondary stat_changes length {len(sec.stat_changes)}"
                    f" exceeds MAX_SECONDARY_STAT_CHANGES={_MAX_SECONDARY_STAT_CHANGES}"
                )
        if len(d.self_stat_changes) > _MAX_SELF_STAT_CHANGES:
            raise ValueError(
                f"{move.name} self_stat_changes length {len(d.self_stat_changes)}"
                f" exceeds MAX_SELF_STAT_CHANGES={_MAX_SELF_STAT_CHANGES}"
            )


def _fmt_stat_changes_array(stat_changes: tuple, max_n: int) -> str:
    """Format a fixed-size inline array of (stat_idx, delta, self_flag) triples, zero-padded."""
    entries = []
    for i in range(max_n):
        if i < len(stat_changes):
            entry = stat_changes[i]
            idx = entry[0]
            delta = entry[1]
            self_flag = 1 if (len(entry) > 2 and entry[2]) else 0
            entries.append(f"{{ {idx}, {delta}, {self_flag} }}")
        else:
            entries.append("{ 0, 0, 0 }")
    return "{ " + ", ".join(entries) + " }"


def _fmt_self_stat_changes_array(self_stat_changes: tuple, max_n: int) -> str:
    """Format a fixed-size inline array of (stat_idx, delta) pairs, zero-padded."""
    entries = []
    for i in range(max_n):
        if i < len(self_stat_changes):
            entry = self_stat_changes[i]
            entries.append(f"{{ {entry[0]}, {entry[1]} }}")
        else:
            entries.append("{ 0, 0 }")
    return "{ " + ", ".join(entries) + " }"


def _fmt_secondary(sec: Optional[SecondaryEffect]) -> str:
    """Format a SecondaryEffect as a C struct literal with full inline stat_changes array."""
    if sec is None:
        empty_array = _fmt_stat_changes_array((), _MAX_SECONDARY_STAT_CHANGES)
        return f"{{ 0, -1, false, 0, false, false, 0, {empty_array} }}"
    status_val = sec.status.value if sec.status is not None else -1
    volatile_flag = 1 if sec.volatile == "confused" else 0
    stat_array = _fmt_stat_changes_array(sec.stat_changes, _MAX_SECONDARY_STAT_CHANGES)
    return (
        f"{{ {sec.chance}, {status_val}, {'true' if sec.flinch else 'false'},"
        f" {volatile_flag}, {'true' if sec.status is not None else 'false'},"
        f" {'true' if sec.volatile is not None else 'false'},"
        f" {len(sec.stat_changes)}, {stat_array} }}"
    )


def _emit_move_data_h() -> str:
    _validate_stat_change_lengths()
    guard = _header_guard("move_data")
    max_sec = _MAX_SECONDARY_STAT_CHANGES
    max_self = _MAX_SELF_STAT_CHANGES
    lines = [
        _file_header(guard, f"MoveData table: {len(MOVE_DATA)} entries."),
        _emit_types_enum(),
        _emit_status_enum(),
        _emit_move_category_enum(),
        _emit_move_target_enum(),
        "",
        f"static const int MAX_SECONDARY_STAT_CHANGES = {max_sec};",
        f"static const int MAX_SELF_STAT_CHANGES = {max_self};",
        "",
        "// One stat change entry: stat_idx (Stat enum value), delta, self_flag (1=self, 0=target).",
        "struct StatChangeEntry {",
        "    int8_t stat_idx;",
        "    int8_t delta;",
        "    int8_t self_flag;",
        "};",
        "",
        "// Secondary effect. All stat_changes entries emitted inline; unused slots zeroed.",
        "struct SecondaryEffect {",
        "    int8_t  chance;               // 0-100",
        "    int8_t  status;               // Status enum value; -1 = none",
        "    bool    flinch;",
        "    int8_t  volatile_confused;    // 1 = inflicts confusion",
        "    bool    has_status;",
        "    bool    has_volatile;",
        f"    int8_t  num_stat_changes;",
        f"    StatChangeEntry stat_changes[{max_sec}];",
        "};",
        "",
        "// One self-stat-change entry applied to user after damage; not suppressed by Sheer Force.",
        "struct SelfStatChangeEntry {",
        "    int8_t stat_idx;",
        "    int8_t delta;",
        "};",
        "",
        "struct MoveData {",
        "    int8_t  move_type;    // Type enum value",
        "    int8_t  category;     // MoveCategory",
        "    uint8_t base_power;",
        "    int8_t  accuracy;     // -1 = always hits",
        "    uint8_t pp;",
        "    int8_t  priority;",
        "    int8_t  target;       // MoveTarget",
        "    int32_t tags;         // MoveTag bitmask",
        "    int8_t  min_hits;",
        "    int8_t  max_hits;",
        "    int8_t  crit_boost;",
        "    int8_t  drain_num;    // drain numerator; -1 = none",
        "    int8_t  drain_den;    // drain denominator",
        "    int8_t  recoil_num;   // recoil numerator; -1 = none",
        "    int8_t  recoil_den;",
        "    SecondaryEffect secondary;",
        "    SecondaryEffect secondary2;",
        f"    int8_t  num_self_stat_changes;",
        f"    SelfStatChangeEntry self_stat_changes[{max_self}];",
        "    int32_t move_id;      // Move enum value",
        "};",
        "",
        f"// Table of {len(MOVE_DATA)} moves, sorted by enum integer value.",
        f"static const MoveData MOVE_TABLE[{len(MOVE_DATA)}] = {{",
    ]

    for move in sorted(MOVE_DATA.keys(), key=lambda m: m.value):
        d: MoveData = MOVE_DATA[move]
        accuracy = _fmt_optional_int(d.accuracy)
        drain_num = d.drain[0] if d.drain else -1
        drain_den = d.drain[1] if d.drain else 0
        recoil_num = d.recoil[0] if d.recoil else -1
        recoil_den = d.recoil[1] if d.recoil else 0
        sec = _fmt_secondary(d.secondary)
        sec2 = _fmt_secondary(d.secondary2)
        self_array = _fmt_self_stat_changes_array(d.self_stat_changes, max_self)
        lines.append(
            f"    {{ {d.move_type.value}, {d.category.value}, {d.base_power},"
            f" {accuracy}, {d.pp}, {d.priority}, {d.target.value}, {int(d.tags)},"
            f" {d.min_hits}, {d.max_hits}, {d.crit_boost},"
            f" {drain_num}, {drain_den}, {recoil_num}, {recoil_den},"
            f" {sec}, {sec2}, {len(d.self_stat_changes)}, {self_array}, {move.value} }},"
            f" // entry {move.name}"
        )

    lines.append("};")
    lines.append(_file_footer(guard))
    return "\n".join(lines)


