def _fmt_float(v: float) -> str:
    """Format float with enough precision to round-trip; no trailing noise."""
    # Use repr-style but strip unnecessary trailing zeros after 6 decimal places
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    if "." not in s:
        s += ".0"
    return s


def _species_weight_literal(species: Species) -> str:
    """Shortest round-trip float literal for a species' authoritative weight.

    Fail loud: every species in SPECIES_DATA must have an entry in SPECIES_WEIGHTS
    (no silent 0.0 default). repr() gives the shortest string that round-trips.
    """
    if species not in SPECIES_WEIGHTS:
        raise KeyError(
            f"SPECIES_WEIGHTS has no weight for {species.name} (value {species.value}); "
            f"regenerate via SCRIPTS/build_species_weights.py"
        )
    return repr(float(SPECIES_WEIGHTS[species]))


def _fmt_optional_int(v: Optional[int]) -> str:
    return str(v) if v is not None else "-1"


def _fmt_optional_float(v: Optional[float]) -> str:
    return _fmt_float(v) if v is not None else "-1.0"


def _fmt_optional_stat(v: Optional[Stat]) -> str:
    return str(v.value) if v is not None else "-1"


def _header_guard(name: str) -> str:
    return f"NUZLOCKE_{name.upper().replace('.', '_')}_H"


def _file_header(guard: str, description: str) -> str:
    return (
        f"// AUTO-GENERATED by SCRIPTS/gen_cpp_data.py — DO NOT EDIT.\n"
        f"// Source of truth: src/data/. Re-run gen_cpp_data.py to update.\n"
        f"// {description}\n"
        f"#pragma once\n"
        f"#ifndef {guard}\n"
        f"#define {guard}\n"
        f"\n"
        f"#include <cstdint>\n"
    )


def _file_footer(guard: str) -> str:
    return f"\n#endif // {guard}\n"


