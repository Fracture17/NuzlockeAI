_EMITTERS: dict[str, callable] = {
    "species_data.h": _emit_species_data_h,
    "move_data.h": _emit_move_data_h,
    "item_data.h": _emit_item_data_h,
    "type_chart.h": _emit_type_chart_h,
    "nature_data.h": _emit_nature_data_h,
    "status.h": _emit_status_h,
    "growth_rate.h": _emit_growth_rate_h,
    "ai_move_sets.h": _emit_ai_move_sets_h,
}


def generate(out_dir: str) -> None:
    """Write all C++ headers to out_dir. Creates the directory if absent."""
    os.makedirs(out_dir, exist_ok=True)
    for filename, emitter in sorted(_EMITTERS.items()):
        content = emitter()
        path = os.path.join(out_dir, filename)
        with open(path, "w", newline="\n") as f:
            f.write(content)


def _check(committed_dir: str) -> list[str]:
    """Regenerate into a temp dir and compare against committed_dir.

    Returns a list of filenames that differ (empty means up-to-date)."""
    with tempfile.TemporaryDirectory() as tmp:
        generate(tmp)
        drifted = []
        for filename in sorted(_EMITTERS.keys()):
            fresh_path = os.path.join(tmp, filename)
            committed_path = os.path.join(committed_dir, filename)
            if not os.path.exists(committed_path):
                drifted.append(filename)
                continue
            fresh = open(fresh_path, "rb").read()
            committed = open(committed_path, "rb").read()
            if fresh != committed:
                drifted.append(filename)
        return drifted


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate C++ data headers from Python src/data/ tables."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify committed headers are up-to-date; exit non-zero if stale.",
    )
    parser.add_argument(
        "--check-dir",
        default=_CPP_GENERATED,
        metavar="DIR",
        help="Directory to compare against during --check (default: cpp/generated/).",
    )
    parser.add_argument(
        "--out",
        default=_CPP_GENERATED,
        metavar="DIR",
        help="Output directory for generated headers (default: cpp/generated/).",
    )
    args = parser.parse_args()

    if args.check:
        drifted = _check(args.check_dir)
        if drifted:
            print("ERROR: the following committed headers are stale vs Python source:")
            for f in drifted:
                print(f"  {f}")
            print("Re-run: python SCRIPTS/gen_cpp_data.py")
            sys.exit(1)
        else:
            print("OK: all headers are up-to-date.")
    else:
        generate(args.out)
        print(f"Generated {len(_EMITTERS)} headers into {args.out}")


if __name__ == "__main__":
    main()
