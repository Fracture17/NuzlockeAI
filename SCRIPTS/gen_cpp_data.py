def _emit_ai_move_sets_h() -> str:
    """Emit move and ability classification sets used by the AI scorer.

    Emits frozensets from moves.py and ai.py as constexpr arrays + counts.
    Also emits _WEATHER_MOVE_TO_WEATHER as parallel move_id/weather int arrays.
    Includes ai_set_contains() inline helper for linear scan membership tests.
    """
    import sys as _sys
    _AI_SRC = "/home/Fracture/PycharmProjects/NuzlockeAI"
    if _AI_SRC not in _sys.path:
        _sys.path.insert(0, _AI_SRC)
    from src.ai import (
        _MOXIE_ABILITIES, _HIGH_CRIT_MOVES, _SPEED_REDUCTION_MOVES,
        _STAT_REDUCTION_DAMAGE_MOVES, _STAT_REDUCTION_ABILITIES,
        _ROLE_PLAY_VALUABLE_ABILITIES, _UNAWARE_SETUP_EXCEPTIONS,
        _WEATHER_MOVE_TO_WEATHER,
    )

    guard = _header_guard("ai_move_sets")
    lines = [
        "// AUTO-GENERATED by SCRIPTS/gen_cpp_data.py — DO NOT EDIT.\n"
        "// Source of truth: src/data/moves.py + src/ai.py. Re-run gen_cpp_data.py to update.\n"
        "// Move and ability classification sets for the AI scorer (ai_scorer.cpp).\n"
        "#pragma once\n"
        f"#ifndef {guard}\n"
        f"#define {guard}\n"
        "\n"
        "#include <cstdint>\n",
    ]

    def emit_int_set(name: str, values, comment_map=None) -> list[str]:
        """Emit a constexpr int32_t array + count for a frozenset of enum values."""
        sorted_vals = sorted(values, key=lambda x: int(x))
        out = [f"static constexpr int32_t {name}[] = {{"]
        for v in sorted_vals:
            comment = f"  // {comment_map(v)}" if comment_map else ""
            out.append(f"    {int(v)},{comment}")
        out.append("};")
        out.append(f"static constexpr int N_{name} = {len(sorted_vals)};")
        return out

    # --- from moves.py ---
    lines += emit_int_set("PROTECT_MOVES", PROTECT_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("WEATHER_RECOVERY_MOVES", WEATHER_RECOVERY_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("RECOVERY_MOVE_SET", RECOVERY_MOVE_SET,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("PARALYSIS_MOVES", PARALYSIS_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("POISON_INFLICT_MOVES", POISON_INFLICT_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("SPEED_SETUP_MOVES", SPEED_SETUP_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("OFFENSIVE_SETUP_MOVES", OFFENSIVE_SETUP_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("DEFENSIVE_SETUP_MOVES", DEFENSIVE_SETUP_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("TERRAIN_MOVES", TERRAIN_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")

    # --- from ai.py ---
    lines += emit_int_set("MOXIE_ABILITIES", _MOXIE_ABILITIES,
                          comment_map=lambda v: Ability(v).name)
    lines.append("")
    lines += emit_int_set("HIGH_CRIT_MOVES", _HIGH_CRIT_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("SPEED_REDUCTION_MOVES", _SPEED_REDUCTION_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("STAT_REDUCTION_DAMAGE_MOVES", _STAT_REDUCTION_DAMAGE_MOVES,
                          comment_map=lambda v: Move(v).name)
    lines.append("")
    lines += emit_int_set("STAT_REDUCTION_ABILITIES", _STAT_REDUCTION_ABILITIES,
                          comment_map=lambda v: Ability(v).name)
    lines.append("")
    lines += emit_int_set("ROLE_PLAY_VALUABLE_ABILITIES", _ROLE_PLAY_VALUABLE_ABILITIES,
                          comment_map=lambda v: Ability(v).name)
    lines.append("")
    lines += emit_int_set("UNAWARE_SETUP_EXCEPTIONS", _UNAWARE_SETUP_EXCEPTIONS,
                          comment_map=lambda v: Move(v).name)
    lines.append("")

    # _WEATHER_MOVE_TO_WEATHER: emit as parallel move_id and weather_id arrays
    sorted_wm2w = sorted(_WEATHER_MOVE_TO_WEATHER.items(), key=lambda kv: int(kv[0]))
    lines.append("// _WEATHER_MOVE_TO_WEATHER: parallel arrays (move_id → weather enum int)")
    lines.append(f"static constexpr int32_t WEATHER_MOVE_IDS[] = {{")
    for mv, _ in sorted_wm2w:
        lines.append(f"    {int(mv)},  // {Move(mv).name}")
    lines.append("};")
    lines.append(f"static constexpr int32_t WEATHER_MOVE_WEATHERS[] = {{")
    for mv, we in sorted_wm2w:
        lines.append(f"    {int(we)},  // {WeatherEnum(we).name}")
    lines.append("};")
    lines.append(f"static constexpr int N_WEATHER_MOVES = {len(sorted_wm2w)};")
    lines.append("")

    # Inline helper for linear-scan membership test
    lines += [
        "// Linear-scan membership test for the arrays above.",
        "inline bool ai_set_contains(const int32_t* arr, int n, int32_t v) {",
        "    for (int i = 0; i < n; ++i) if (arr[i] == v) return true;",
        "    return false;",
        "}",
        "",
        f"#endif // {guard}",
    ]

    return "\n".join(lines) + "\n"


