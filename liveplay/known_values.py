# A move can appear in a "used <move>!" message via direct use OR a Metronome call,
# so the matcher must be able to parse the display name of EVERY implemented move.
# Per project rule "implemented = in the Move enum", union in the display name of
# every Move enum member (this supersedes the older Metronome-callable-only union,
# which wrongly excluded in-enum-but-METRONOME_EXCLUDED moves like Heal Pulse, Dig,
# Counter, etc. — Issue 22). Moves absent from the enum (unmodeled romhack additions)
# remain unparseable — accepted per scope.
def _all_move_display_names() -> frozenset[str]:
    from liveplay.data.moves import Move
    return frozenset(m.name.replace("_", " ") for m in Move if m.name != "NONE")


