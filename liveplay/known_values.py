# The base frozenset above is vanilla-Emerald-only (Gen 1-3). Run & Bun adds the
# full Gen 4-8 roster, so an OCR'd name like "Budew" hits the unconstrained
# validation path (constraints=None) and is rejected, crashing the matcher.
# Mirror MOVE_NAMES: union in the emulator display name of EVERY Species enum
# member. Forms render under their base name (handled by emulator_species_name),
# and extra form names only loosen unconstrained validation — they never reject a
# real OCR name, since every base name is present.
def _all_species_display_names() -> frozenset[str]:
    from liveplay.data.species import Species
    from liveplay.data.name_aliases import emulator_species_name
    return frozenset(emulator_species_name(s).upper() for s in Species)


